#!/usr/bin/env bash
set -euo pipefail

# Prints a base pipeline plus a resource and test-<name> job per test/resources/<name>/, and test-full:
# every test's test.sh against the deep merge of all source.yml files. Needs mikefarah yq v4.

usage() {
  echo "usage: $0 <base pipeline> [--no-rootless]" >&2
  exit 2
}

export LC_ALL=C
RESOURCES="$(cd "$(dirname "$0")" && pwd)/resources"
export TASK_FILE=repo/test/resources/task.yml

base=""
rootless=true
while (($#)); do
  case "$1" in
    --no-rootless) rootless=false ;;
    -*) usage ;;
    *) [[ -z "$base" ]] || usage; base="$1" ;;
  esac
  shift
done
[[ -f "$base" ]] || usage

export TMP_DIR
TMP_DIR="$(mktemp -d)"
trap 'rm -rf "$TMP_DIR"' EXIT

tests=()
for dir in "$RESOURCES"/*; do
  name="$(basename "$dir")"
  [[ -f "$dir/source.yml" || -f "$dir/test.sh" ]] || continue
  if [[ ! -f "$dir/source.yml" || ! -f "$dir/test.sh" ]]; then
    echo "test/resources/$name needs both source.yml and test.sh" >&2
    exit 1
  fi
  tests+=("$name")
done

# One "path<TAB>value<TAB>test" line per map entry; list items are skipped because lists are unioned.
source_entries() {
  yq '.. | select((path | length) > 0 and (path | all_c(tag == "!!str")))
    | (path | join(".")) + "	" + ((select(tag == "!!map" or tag == "!!seq") | tag) // to_json(0))' \
    "$RESOURCES/$1/source.yml" | sed "s/\$/	$1/"
}

for test in "${tests[@]}"; do source_entries "$test"; done | awk -F'\t' '
  ($1 in value) && value[$1] != $2 {
    printf "conflicting source.yml values, %s: %s in %s but %s in %s\n", $1, value[$1], owner[$1], $2, $3 > "/dev/stderr"
    failed = 1
  }
  !($1 in value) { value[$1] = $2; owner[$1] = $3 }
  END { exit failed }'

apply_local_flags() {
  ROOTLESS="$rootless" yq '(. // {})
    | with(select(strenv(ROOTLESS) == "false" and .testcontainers.rootless != null); .testcontainers.rootless = false)' "$1"
}

for test in "${tests[@]}"; do
  apply_local_flags "$RESOURCES/$test/source.yml" > "$TMP_DIR/$test.yml"
done
source_files=()
for test in "${tests[@]}"; do source_files+=("$RESOURCES/$test/source.yml"); done
yq ea '(. // {}) as $source ireduce ({}; . *+ $source) | (.. | select(tag == "!!seq")) |= unique' "${source_files[@]}" \
  | apply_local_flags - > "$TMP_DIR/full.yml"

# One-item list per step, so steps concatenate with `+`. Images with testcontainers start a container runtime.
step_yaml() {
  local privileged
  privileged="$(yq '.testcontainers.enabled == true' "$TMP_DIR/$2.yml")"
  TEST_NAME="$1" IMAGE="setup-runtime-$2" PRIVILEGED="$privileged" yq -n '[{"task": strenv(TEST_NAME), "image": strenv(IMAGE)}
    | with(select(env(PRIVILEGED)); .privileged = true)
    | .file = strenv(TASK_FILE) | .params.TEST = strenv(TEST_NAME)]'
}

has_build_job="$(yq '.jobs | any_c(.name == "build")' "$base")"
job_yaml() {
  NAME="$1" IMAGE="setup-runtime-$2" HAS_BUILD_JOB="$has_build_job" STEPS="$3" yq -n '[{"name": "test-" + strenv(NAME), "serial": true}
    | .plan = [{"in_parallel": [{"get": strenv(IMAGE)}, {"get": "repo"}]}]
    | with(select(env(HAS_BUILD_JOB)); .plan[0].in_parallel[1].passed = ["build"])
    | .plan += (load(strenv(STEPS)) | with(select(strenv(NAME) == "full"); . = [{"in_parallel": .}]))]'
}

resource_yaml() {
  NAME="$1" yq -n '[{"name": "setup-runtime-" + strenv(NAME), "type": "setup-runtime-resource",
    "icon": "account-hard-hat", "source": load(strenv(TMP_DIR) + "/" + strenv(NAME) + ".yml")}]'
}

concat_lists() { yq ea '. as $item ireduce ([]; . + $item)' "$@"; }

for test in "${tests[@]}"; do
  step_yaml "$test" full > "$TMP_DIR/full-step-$test.yml"
  step_yaml "$test" "$test" > "$TMP_DIR/step-$test.yml"
  job_yaml "$test" "$test" "$TMP_DIR/step-$test.yml" > "$TMP_DIR/job-$test.yml"
  resource_yaml "$test" > "$TMP_DIR/resource-$test.yml"
done
rendered_files() { local test; for test in "${tests[@]}"; do echo "$TMP_DIR/$1-$test.yml"; done; }
mapfile -t full_steps < <(rendered_files full-step)
mapfile -t jobs < <(rendered_files job)
mapfile -t resources < <(rendered_files resource)
concat_lists "${full_steps[@]}" > "$TMP_DIR/full-steps.yml"
job_yaml full full "$TMP_DIR/full-steps.yml" > "$TMP_DIR/job-full.yml"
resource_yaml full > "$TMP_DIR/resource-full.yml"
concat_lists "$TMP_DIR/job-full.yml" "${jobs[@]}" > "$TMP_DIR/jobs.yml"
concat_lists "$TMP_DIR/resource-full.yml" "${resources[@]}" > "$TMP_DIR/resources.yml"

echo "# Generated by test/pipeline.sh from $base; edit that file instead."
yq '.resources += load(strenv(TMP_DIR) + "/resources.yml")
  | .jobs += load(strenv(TMP_DIR) + "/jobs.yml")' \
  "$base"
